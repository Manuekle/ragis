"""Curated Croma catalog (ADR-036): which public-record lookups Ask may run, and how to fill them.

`croma_catalog.json` is generated by `scripts/croma-catalog.py` from Croma's public catalog and only holds the
allowlist (companies, court cases, laws, regulation, sanctions, procurement, statistics, the web). Lookups of a
private person's data by ID number are never in it, so neither the model nor the user can reach them.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from ragsis_core.text import fold

CATALOG_FILE = Path(__file__).with_name("croma_catalog.json")

COUNTRY_NAMES: dict[str, str] = {
    "co": "Colombia", "mx": "Mexico", "pe": "Peru", "us": "United States", "br": "Brazil", "sv": "El Salvador",
    "bo": "Bolivia", "jp": "Japan", "cl": "Chile", "ve": "Venezuela", "gt": "Guatemala", "global": "Worldwide",
}
COUNTRY_CODES = tuple(c for c in COUNTRY_NAMES if c != "global")

# Country named in the question (folded text: no accents, lower case). "global" = worldwide / international.
_COUNTRY_RX: dict[str, re.Pattern[str]] = {
    "co": re.compile(r"\bcolombi(a|an[oa]s?|ans?)\b"),
    "mx": re.compile(r"\bmexic(o|an[oa]s?|ans?)\b"),
    "pe": re.compile(r"\bperu(an[oa]s?|vian?s?)?\b"),
    "us": re.compile(r"\b(estados unidos|ee\.? ?uu\.?|usa|united states|estadounidenses?|norteamerican[oa]s?)\b"),
    "br": re.compile(r"\b(brasil|brazil|brasilen[oa]s?|brazilians?|brasileir[oa]s?)\b"),
    "sv": re.compile(r"\b(el salvador|salvadoren[oa]s?|salvadorans?)\b"),
    "bo": re.compile(r"\bbolivi(a|an[oa]s?|ans?)\b"),
    "jp": re.compile(r"\b(japon|japan|japones[ae]?s?|japanese)\b"),
    "cl": re.compile(r"\bchile(n[oa]s?|ans?)?\b"),
    "ve": re.compile(r"\bvenezuel(a|an[oa]s?|ans?)\b"),
    "gt": re.compile(r"\bguatemal(a|tec[oa]s?|ans?)\b"),
    "global": re.compile(r"\b(internacional(es)?|international|mundial(es)?|worldwide|global(es)?|en el mundo|"
                         r"otros paises|other countries|around the world)\b"),
}


@dataclass(frozen=True)
class Param:
    name: str
    type: str
    required: bool
    enum: tuple | None = None
    min_length: int | None = None
    max_length: int | None = None
    minimum: float | None = None
    maximum: float | None = None
    pattern: str | None = None
    description: str = ""

    def hint(self) -> str:
        """One-line description for the planner prompt."""
        bits = [self.type]
        if self.required:
            bits.append("required")
        if self.enum:
            bits.append("one of " + "/".join(str(v) for v in self.enum[:8]))
        if self.pattern and self.type == "string":
            bits.append(f"format {self.pattern}")
        text = f"{self.name} ({', '.join(bits)})"
        if self.description:
            text += f": {self.description[:90]}"
        return text


@dataclass(frozen=True)
class Endpoint:
    id: str
    name: str
    path: str
    country: str
    source: str
    category: str
    served_from: str
    description: str
    docs_url: str
    text_param: str | None
    params: tuple[Param, ...]

    @property
    def credits(self) -> int:
        """Croma credits per call: a dataset answer costs 1, a live lookup 10 (cache hits cost nothing)."""
        return 1 if self.served_from == "dataset" else 10

    @property
    def kind(self) -> str:
        return "web" if self.category == "web" else "public_record"

    def param(self, name: str) -> Param | None:
        return next((p for p in self.params if p.name == name), None)

    def prompt_params(self, limit: int = 5) -> list[Param]:
        """Required params first, then the free-text one, then short optional filters (paging excluded)."""
        skip = {"page", "per_page", "page_size", "offset", "cursor"}
        ordered = [p for p in self.params if p.required]
        if self.text_param and not any(p.name == self.text_param for p in ordered):
            tp = self.param(self.text_param)
            if tp:
                ordered.append(tp)
        ordered += [p for p in self.params if p not in ordered and p.name not in skip]
        return ordered[:limit]


def _param(raw: dict) -> Param:
    enum = raw.get("enum")
    return Param(
        name=str(raw["name"]), type=str(raw.get("type") or "string"), required=bool(raw.get("required")),
        enum=tuple(enum) if isinstance(enum, list) else None, min_length=raw.get("minLength"),
        max_length=raw.get("maxLength"), minimum=raw.get("minimum"), maximum=raw.get("maximum"),
        pattern=raw.get("pattern"), description=str(raw.get("description") or ""),
    )


@lru_cache
def load_catalog() -> dict[str, Endpoint]:
    raw = json.loads(CATALOG_FILE.read_text(encoding="utf-8"))
    out: dict[str, Endpoint] = {}
    for e in raw["endpoints"]:
        if not str(e["path"]).startswith("/") or ".." in e["path"]:
            continue  # defensa: solo rutas relativas del host fijo de Croma
        out[e["id"]] = Endpoint(
            id=e["id"], name=e["name"], path=e["path"], country=e["country"], source=e["source"],
            category=e["category"], served_from=e["served_from"], description=e["description"],
            docs_url=e.get("docs_url") or "", text_param=e.get("text_param"),
            params=tuple(_param(p) for p in e["params"]),
        )
    return out


def countries_in(question: str) -> list[str]:
    folded = fold(question)
    return [code for code, rx in _COUNTRY_RX.items() if rx.search(folded)]


def endpoints_for(countries: list[str], web: bool) -> list[Endpoint]:
    """Shortlist for the planner: the countries' registries plus the worldwide tools (web only if allowed)."""
    want = set(countries) | {"global"}
    return [e for e in load_catalog().values()
            if e.country in want and (web or e.category != "web")]
