def long_date(d: date, language: str) -> str:
    month = _MONTHS[language][d.month - 1]
    return f"{d.day} de {month} de {d.year}" if language == "es" else f"{d.day} {month} {d.year}"


def source_label(s: Source, language: str) -> str:
    """«Política de viajes — v3 · p. 4 · Reembolsos · vigente desde 2026-01-01»."""
    lab = LABELS[language]
    parts = []
    if s.version_no:
        parts.append(f"{lab['version']}{s.version_no}")
    if s.page:
        parts.append(f"{lab['p']} {s.page}")
    if s.t_start is not None:
        m, sec = divmod(int(s.t_start), 60)
        parts.append(f"{lab['at']} {m:02d}:{sec:02d}")
    if s.section:
        parts.append(s.section)
    if s.effective_from:
        parts.append(f"{lab['effective']} {s.effective_from}")
    return s.title + (" — " + " · ".join(parts) if parts else "")


def short_source(s: Source, language: str) -> str:
    """Versión corta para tablas y pies de diapositiva: «Política de viajes, p. 4»."""
    lab = LABELS[language]
    return s.title + (f", {lab['p']} {s.page}" if s.page else "")


def plain(runs: list[Run] | None) -> str:
    if not runs:
        return ""
    return "".join(f"[{r.cite}]" if r.cite is not None else r.text for r in runs).strip()


def cites_in(runs: list[Run]) -> list[int]:
    return [r.cite for r in runs if r.cite is not None]


def slug(title: str, fallback: str = "document") -> str:
    s = re.sub(r"[^a-z0-9]+", "-", fold(title)).strip("-")
    return (s[:60].rstrip("-") or fallback)


# ----------------------------------------------------------------------------------------------------------------
# Parsing

_CITE_AFTER_PUNCT = re.compile(r"(?<=[^\s.!?;:])([.!?;:])[ \t]*(\[\d{1,2}\](?:[ \t]*\[\d{1,2}\])*)(?=[ \t]*(?:$|[\s|]))",
                               re.M)
_LIST_MARKER = re.compile(r"^\s*(?:[-*+]\s+)?\d{1,3}$")


def tidy_citations(markdown: str) -> str:
    """«…de 2026. [4]» → «…de 2026 [4].»: the citation goes before the sentence's closing mark, so it never ends up
    alone at the start of a line in the PDF or a slide. An ordered-list marker («1. [2] …») is left alone."""
    def move(m: re.Match) -> str:
        line_start = m.string.rfind("\n", 0, m.start()) + 1
        if _LIST_MARKER.match(m.string[line_start:m.start()]):
            return m.group(0)
        return f" {re.sub(r'[ \t]+', '', m.group(2))}{m.group(1)}"
    return _CITE_AFTER_PUNCT.sub(move, markdown)


def _bind_cites(runs: list[Run]) -> list[Run]:
    """The space before a citation becomes non-breaking: «2026 [4]» stays on one line in every format."""
    for prev, cur in zip(runs, runs[1:], strict=False):
        if cur.cite is not None and prev.cite is None and not prev.code and prev.text[-1:].isspace():
            prev.text = prev.text.rstrip() + " "
    return runs


def _split_cites(run: Run) -> list[Run]:
    if run.code or run.cite is not None or "[" not in run.text:
        return [run]
    out: list[Run] = []
    pos = 0
    for m in _CITE_RX.finditer(run.text):
        if m.start() > pos:
            out.append(Run(run.text[pos:m.start()], run.bold, run.italic, run.code, run.strike, run.href))
        out.append(Run("", cite=int(m.group(1))))
        pos = m.end()
    if pos < len(run.text):
        out.append(Run(run.text[pos:], run.bold, run.italic, run.code, run.strike, run.href))
    return out


def _inline(token) -> list[Run]:
    runs: list[Run] = []
    bold = italic = strike = False
    href: str | None = None
    for ch in token.children or []:
        t = ch.type
        if t == "text":
            runs.append(Run(ch.content, bold, italic, False, strike, href))
        elif t == "code_inline":
            runs.append(Run(ch.content, bold, italic, True, strike, href))
        elif t in ("softbreak", "hardbreak"):
            runs.append(Run(" "))
        elif t == "strong_open":
            bold = True
        elif t == "strong_close":
            bold = False
        elif t == "em_open":
            italic = True
        elif t == "em_close":
            italic = False
        elif t == "s_open":
            strike = True
        elif t == "s_close":
            strike = False
        elif t == "link_open":
            target = str(ch.attrs.get("href") or "")
            href = target if target.startswith(("http://", "https://", "mailto:")) else None
        elif t == "link_close":
            href = None
        elif t == "image":
            # Las imágenes no se descargan nunca; queda el texto alternativo.
            alt = ch.content or "".join(c.content for c in ch.children or [])
            if alt:
                runs.append(Run(alt, bold, True, False, strike))
    split = [piece for r in runs for piece in _split_cites(r)]
    # Unir textos contiguos con el mismo formato: menos fragmentos en Word y PowerPoint.
    merged: list[Run] = []
    for r in split:
        last = merged[-1] if merged else None
        if (last and r.cite is None and last.cite is None and (last.bold, last.italic, last.code, last.strike, last.href)
                == (r.bold, r.italic, r.code, r.strike, r.href)):
            last.text += r.text
        else:
            merged.append(r)
    return _bind_cites([r for r in merged if r.cite is not None or r.text])


def _strip_trailing_space(runs: list[Run]) -> list[Run]:
    if runs and runs[0].cite is None:
        runs[0].text = runs[0].text.lstrip()
    if runs and runs[-1].cite is None:
        runs[-1].text = runs[-1].text.rstrip()
    return [r for r in runs if r.cite is not None or r.text]


def parse_blocks(markdown: str) -> list[Block]:
    tokens = _MD.parse(markdown[:MAX_MARKDOWN_CHARS])
    blocks: list[Block] = []
    i = 0
    list_stack: list[dict] = []        # [{ordered, number}]
    current_list: ListBlock | None = None
    quote_depth = 0
    quote_runs: list[Run] = []
    table: Table | None = None
    row: list[list[Run]] | None = None
    in_head = False
    item_open: list[ListItem | None] = []

    while i < len(tokens):
        tk = tokens[i]
        t = tk.type
        if t == "heading_open":
            runs = _strip_trailing_space(_inline(tokens[i + 1]))
            if runs:
                blocks.append(Heading(int(tk.tag[1]), runs))
            i += 3
            continue
        if t in ("bullet_list_open", "ordered_list_open"):
            start = int(tk.attrs.get("start") or 1) if t == "ordered_list_open" else 1
            list_stack.append({"ordered": t == "ordered_list_open", "number": start})
            if current_list is None:
                current_list = ListBlock([])
        elif t in ("bullet_list_close", "ordered_list_close"):
            list_stack.pop()
            if not list_stack and current_list is not None:
                if current_list.items:
                    blocks.append(current_list)
                current_list = None
        elif t == "list_item_open":
            item_open.append(None)
        elif t == "list_item_close":
            item_open.pop()
            if list_stack:
                list_stack[-1]["number"] += 1
        elif t == "blockquote_open":
            quote_depth += 1
        elif t == "blockquote_close":
            quote_depth -= 1
            if quote_depth == 0 and quote_runs:
                blocks.append(Quote(_strip_trailing_space(quote_runs)))
                quote_runs = []
        elif t == "table_open":
            table = Table([], [])
        elif t == "table_close":
            if table and table.header:
                blocks.append(table)
            table = None
        elif t == "thead_open":
            in_head = True
        elif t == "thead_close":
            in_head = False
        elif t == "tr_open":
            row = []
        elif t == "tr_close" and table is not None and row is not None:
            if in_head:
                table.header = row
            elif any(plain(c) for c in row):
                table.rows.append(row)
            row = None
        elif t in ("th_open", "td_open"):
            style = str(tk.attrs.get("style") or "")
            if in_head and table is not None:
                table.align.append("center" if "center" in style else "right" if "right" in style else "left")
            cell = _strip_trailing_space(_inline(tokens[i + 1]))
            if row is not None:
                row.append(cell)
            i += 3
            continue
        elif t == "paragraph_open":
            runs = _strip_trailing_space(_inline(tokens[i + 1]))
            if runs:
                if list_stack and current_list is not None and item_open:
                    top = list_stack[-1]
                    existing = item_open[-1]
                    if existing is None:
                        item = ListItem(runs, len(list_stack) - 1, top["ordered"], top["number"])
                        current_list.items.append(item)
                        item_open[-1] = item
                    else:
                        existing.runs += [Run(" "), *runs]
                elif quote_depth:
                    quote_runs += ([Run(" ")] if quote_runs else []) + runs
                else:
                    blocks.append(Paragraph(runs))
            i += 3
            continue
        elif t in ("fence", "code_block"):
            if tk.content.strip():
                blocks.append(Code(tk.content.rstrip("\n")))
        elif t == "hr":
            blocks.append(Rule())
        i += 1
    return blocks


def _unwrap_fence(markdown: str) -> str:
    """Algunos modelos envuelven todo el documento en ```markdown … ```."""
    m = re.fullmatch(r"\s*```(?:markdown|md)?\s*\n(.*?)\n```\s*", markdown, re.S | re.I)
    return m.group(1) if m else markdown


def build_document(markdown: str, citations: list[dict], *, kind: str = "report", fallback_title: str = "Document",
                   created: date | None = None, language: str | None = None) -> Document:
    """Documento listo para renderizar. Título = primer H1 (o `fallback_title`); entradilla = párrafo que lo sigue."""
    blocks = parse_blocks(tidy_citations(_unwrap_fence(markdown)))
    title = ""
    lead: list[Run] | None = None
    if blocks and isinstance(blocks[0], Heading) and blocks[0].level == 1:
        title = plain(blocks.pop(0).runs)
        if blocks and isinstance(blocks[0], Paragraph):
            lead = blocks.pop(0).runs
    # El título nunca lleva citas visibles.
    title = _CITE_RX.sub("", title).strip() or fallback_title
    headings = [b.level for b in blocks if isinstance(b, Heading)]
    if headings:
        shift = min(headings) - 1
        for b in blocks:
            if isinstance(b, Heading):
                b.level = max(1, min(3, b.level - shift))
    used = {r.cite for b in blocks for r in _block_runs(b) if r.cite is not None} | set(cites_in(lead or []))
    sources = sorted((Source.from_citation(c) for c in citations if int(c.get("n", 0)) in used), key=lambda s: s.n)
    lang = language or ("es" if looks_spanish(f"{title} {plain(lead)} " + " ".join(
        plain(r) for b in blocks[:12] for r in [_block_runs(b)])) else "en")
    return Document(title[:200], lead, blocks, sources, kind, lang, created or date.today())


def _block_runs(b: Block) -> list[Run]:
    if isinstance(b, Heading | Paragraph | Quote):
        return b.runs
    if isinstance(b, ListBlock):
        return [r for it in b.items for r in it.runs]
    if isinstance(b, Table):
        return [r for cell in b.header for r in cell] + [r for row in b.rows for cell in row for r in cell]
    return []


def outline(doc: Document) -> list[str]:
    """Títulos de sección de primer nivel (para la tarjeta del chat)."""
    return [plain(b.runs) for b in doc.blocks if isinstance(b, Heading) and b.level == 1][:20]


def word_count(doc: Document) -> int:
    text = " ".join([doc.title, plain(doc.lead)] + [plain(_block_runs(b)) for b in doc.blocks])
    return len(_CITE_RX.sub("", text).split())
