"""Markdown → modelo intermedio del documento (ADR-034).

El Markdown es la fuente única: el modelo lo escribe, el verificador lo depura y se guarda tal cual. Cada formato de
salida (PDF, Word, PowerPoint, CSV) se renderiza desde este modelo intermedio, así que todos muestran lo mismo:
mismo título, mismas secciones, mismas citas [n] y la misma lista de fuentes al final.

No hay HTML ni imágenes remotas: markdown-it corre sin HTML y los enlaces se conservan como texto con su URL. Ningún
renderizador descarga nada, así que un documento no puede usarse para hacer peticiones desde el servidor.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import date

from markdown_it import MarkdownIt
from ragsis_core.text import fold

from ..prompting import looks_spanish

_CITE_RX = re.compile(r"\[(\d{1,2})\]")
_MD = MarkdownIt("commonmark", {"html": False, "linkify": False, "typographer": False}).enable(["table", "strikethrough"])
MAX_MARKDOWN_CHARS = 200_000


@dataclass
class Run:
    text: str
    bold: bool = False
    italic: bool = False
    code: bool = False
    strike: bool = False
    href: str | None = None
    cite: int | None = None


@dataclass
class Heading:
    level: int                # 1 = sección (el título del documento va aparte)
    runs: list[Run]


@dataclass
class Paragraph:
    runs: list[Run]


@dataclass
class ListItem:
    runs: list[Run]
    level: int = 0
    ordered: bool = False
    number: int = 1


@dataclass
class ListBlock:
    items: list[ListItem]


@dataclass
class Table:
    header: list[list[Run]]
    rows: list[list[list[Run]]]
    align: list[str] = field(default_factory=list)   # "left" | "center" | "right"


@dataclass
class Quote:
    runs: list[Run]


@dataclass
class Code:
    text: str


@dataclass
class Rule:
    pass


Block = Heading | Paragraph | ListBlock | Table | Quote | Code | Rule


@dataclass
class Source:
    n: int
    title: str
    filename: str = ""
    version_no: int | None = None
    page: int | None = None
    section: str = ""
    effective_from: str | None = None
    kind: str = "text"
    t_start: float | None = None

    @classmethod
    def from_citation(cls, c: dict) -> Source:
        def _int(v):
            try:
                return int(v) if v is not None else None
            except (TypeError, ValueError):
                return None
        t = c.get("t_start")
        return cls(n=int(c["n"]), title=str(c.get("title") or c.get("filename") or f"Source {c['n']}")[:200],
                   filename=str(c.get("filename") or "")[:200], version_no=_int(c.get("version_no")),
                   page=_int(c.get("page")), section=str(c.get("section") or "")[:160],
                   effective_from=c.get("effective_from"), kind=str(c.get("kind") or "text"),
                   t_start=float(t) if isinstance(t, int | float) else None)


@dataclass
class Document:
    title: str
    lead: list[Run] | None
    blocks: list[Block]
    sources: list[Source]
    kind: str = "report"          # report | presentation | table
    language: str = "en"
    created: date = field(default_factory=date.today)

    @property
    def labels(self) -> dict[str, str]:
        return LABELS[self.language]

    def source(self, n: int) -> Source | None:
        return next((s for s in self.sources if s.n == n), None)


