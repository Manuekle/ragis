import { localePath, usdFor } from "@/lib/i18n";
import { getLocale } from "@/lib/locale";
import { contentFor } from "../(public)/content";
import { everyPlanFor, plansFor } from "../(public)/pricing/plans";
import { absoluteUrl, PUBLIC_PAGES, pageInfo, site, SITE_TEXT } from "../(public)/site";

// Read PUBLIC_BASE_URL when served, not when built (see robots.ts).
export const dynamic = "force-dynamic";


/**
 * /llms.txt (https://llmstxt.org): Ragis in plain Markdown for AI assistants and answer engines,
 * so they can describe and cite it without running the landing's scripts. Built from the same
 * words the pages show (content.ts, plans.ts, site.ts); change those, not this.
 */
export async function GET() {
  const locale = await getLocale();
  const es = locale === "es";
  const text = SITE_TEXT[locale];
  const usd = usdFor(locale);
  const { FEATURES, LANDING_FAQ, STEPS, TRUST } = contentFor(locale);
  const lines = [
    `# ${site.name}`,
    "",
    `> ${text.description}`,
    "",
    es
      ? `${site.name} está en acceso anticipado: las empresas se unen a la lista de espera en ${absoluteUrl(localePath(locale, "/waitlist"))} y se las invita en grupos pequeños. Las respuestas salen solo de los documentos del propio cliente, nunca de la web abierta, y el contenido del cliente nunca se usa para entrenar modelos de IA.`
      : `${site.name} is in early access: companies join the waitlist at ${absoluteUrl("/waitlist")} and are invited in small groups. Answers come only from the customer's own documents, never from the open web, and customer content is never used to train AI models.`,
    "",
    es ? "## Cómo funciona" : "## How it works",
    "",
    ...STEPS.map((step, i) => `${i + 1}. **${step.title}.** ${step.text}`),
    "",
    es ? "## Qué hace" : "## What it does",
    "",
    es ? "- **Respuestas citadas.** Cada afirmación de una respuesta enlaza al documento y la página de los que sale." : "- **Cited answers.** Every claim in an answer links to the document and page it came from.",
    ...FEATURES.map((feature) => `- **${feature.title}.** ${feature.text}`),
    "",
    es ? "## Seguridad y privacidad" : "## Security and privacy",
    "",
    ...TRUST.map((item) => `- **${item.title}.** ${item.text}`),
    es
      ? "- **Sin entrenar con tu contenido.** Los documentos y las preguntas de los clientes no se usan para entrenar modelos de IA, y los datos personales no se venden."
      : "- **No training on your content.** Customer documents and questions are not used to train AI models, and personal data is not sold.",
    es
      ? "- **Dónde se ejecuta.** Las respuestas las generan modelos de Amazon Bedrock en la región acordada con el cliente, o en los propios servidores del cliente con modelos locales (autoalojado)."
      : "- **Where it runs.** Answers are generated by models on Amazon Bedrock in the region agreed with the customer, or on the customer's own servers with local models (self-hosted).",
    "",
    es ? "## Precios" : "## Pricing",
    "",
    es ? "Precios en USD, facturados mensual o anualmente; el formulario de pedido confirma el precio final y las cuotas." : "Prices in USD, billed monthly or annually; the order form confirms the final price and quotas.",
    "",
    ...plansFor(locale).map((plan) => (es ? `- **${plan.name}:** desde ${usd.format(plan.monthlyPrice)} al mes más ${plan.additionalCost}. ${plan.blurb} Incluye ${plan.features.join(", ")}.` : `- **${plan.name}:** from ${usd.format(plan.monthlyPrice)} a month plus ${plan.additionalCost}. ${plan.blurb} Includes ${plan.features.join(", ")}.`)),
    es ? "- **Autoalojado:** licencia anual con implementación y soporte, ejecutándose en la infraestructura del cliente con modelos locales." : "- **Self-hosted:** annual license with implementation and support, running on the customer's infrastructure with local models.",
    "",
    es ? `Todos los planes incluyen: ${everyPlanFor(locale).join("; ")}. Detalles: ${absoluteUrl(localePath(locale, "/pricing"))}` : `Every plan includes: ${everyPlanFor(locale).join("; ")}. Details: ${absoluteUrl("/pricing")}`,
    "",
    es ? "## Preguntas frecuentes" : "## Frequently asked questions",
    "",
    ...LANDING_FAQ.flatMap((item) => [`### ${item.q}`, "", item.text, ""]),
    es ? "## Páginas" : "## Pages",
    "",
    ...PUBLIC_PAGES.map((page) => `- [${pageInfo(locale, page.path).title}](${absoluteUrl(localePath(locale, page.path))}): ${pageInfo(locale, page.path).summary}`),
    "",
  ];

  return new Response(lines.join("\n"), {
    headers: { "Content-Type": "text/markdown; charset=utf-8", "Cache-Control": "public, max-age=3600" },
  });
}
