import { FEATURES, LANDING_FAQ, STEPS, TRUST } from "../(public)/content";
import { EVERY_PLAN, PLANS } from "../(public)/pricing/plans";
import { absoluteUrl, PUBLIC_PAGES, site } from "../(public)/site";

// Read PUBLIC_BASE_URL when served, not when built (see robots.ts).
export const dynamic = "force-dynamic";

const usd = new Intl.NumberFormat("en-US", { style: "currency", currency: "USD", minimumFractionDigits: 0 });

/**
 * /llms.txt (https://llmstxt.org): Ragis in plain Markdown for AI assistants and answer engines,
 * so they can describe and cite it without running the landing's scripts. Built from the same
 * words the pages show (content.ts, plans.ts, site.ts); change those, not this.
 */
export function GET() {
  const lines = [
    `# ${site.name}`,
    "",
    `> ${site.description}`,
    "",
    `${site.name} is in early access: companies join the waitlist at ${absoluteUrl("/waitlist")} and are invited in small groups. Answers come only from the customer's own documents, never from the open web, and customer content is never used to train AI models.`,
    "",
    "## How it works",
    "",
    ...STEPS.map((step, i) => `${i + 1}. **${step.title}.** ${step.text}`),
    "",
    "## What it does",
    "",
    "- **Cited answers.** Every claim in an answer links to the document and page it came from.",
    ...FEATURES.map((feature) => `- **${feature.title}.** ${feature.text}`),
    "",
    "## Security and privacy",
    "",
    ...TRUST.map((item) => `- **${item.title}.** ${item.text}`),
    "- **No training on your content.** Customer documents and questions are not used to train AI models, and personal data is not sold.",
    "- **Where it runs.** Answers are generated by models on Amazon Bedrock in the region agreed with the customer, or on the customer's own servers with local models (self-hosted).",
    "",
    "## Pricing",
    "",
    "Prices in USD, billed monthly or annually; the order form confirms the final price and quotas.",
    "",
    ...PLANS.map((plan) => `- **${plan.name}:** from ${usd.format(plan.monthlyPrice)} a month plus ${plan.additionalCost}. ${plan.blurb} Includes ${plan.features.join(", ")}.`),
    "- **Self-hosted:** annual license with implementation and support, running on the customer's infrastructure with local models.",
    "",
    `Every plan includes: ${EVERY_PLAN.join("; ")}. Details: ${absoluteUrl("/pricing")}`,
    "",
    "## Frequently asked questions",
    "",
    ...LANDING_FAQ.flatMap((item) => [`### ${item.q}`, "", item.text, ""]),
    "## Pages",
    "",
    ...PUBLIC_PAGES.map((page) => `- [${page.title}](${absoluteUrl(page.path)}): ${page.summary}`),
    "",
  ];

  return new Response(lines.join("\n"), {
    headers: { "Content-Type": "text/markdown; charset=utf-8", "Cache-Control": "public, max-age=3600" },
  });
}
